import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync,spawnSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
test('documentation checkpoints catch missing and changed-again files and preserve version history',()=>{
 const fixture=mkdtempSync(path.join(tmpdir(),'zoltraak-changelog-'));
 try{
  for(const directory of ['app/src-tauri','app/public','extension','scripts/templates','scripts'])mkdirSync(path.join(fixture,directory),{recursive:true});
  const write=(file,text)=>writeFileSync(path.join(fixture,file),text);
  write('app/package.json','{"version":"0.2.5"}');write('app/src-tauri/tauri.conf.json','{"version":"0.2.5"}');
  write('app/package-lock.json',JSON.stringify({version:'0.2.5',packages:{'':{version:'0.2.5'},'node_modules/example':{version:'2.0.0'}}}));
  write('app/src-tauri/Cargo.lock','[[package]]\nname = "zoltraak-app"\nversion = "0.2.5"\n\n[[package]]\nname = "third-party"\nversion = "2.0.0"\n');
  write('scripts/templates/guide.html','<html><head></head><body><script>const htmlEl=document.documentElement;</script>    <!-- Footer --></body></html>');
  write('scripts/templates/legal.html','<html><body><h1>Windows legal notice</h1><script>window.legalFixture=true;</script></body></html>');
  write('scripts/changelog-view.js',readFileSync(path.join(root,'scripts/changelog-view.js'),'utf8'));
  write('feature.txt','original');
  write('local-only.txt','keep this local copy');
  const git=(...args)=>execFileSync('git',args,{cwd:fixture,encoding:'utf8'}).trim();
  git('init');git('add','.');git('-c','user.name=Fixture','-c','user.email=fixture@example.test','commit','-m','baseline');
  const log={schemaVersion:1,development:{version:'0.2.5',previousVersion:'0.2.4',baselineCommit:git('rev-parse','HEAD'),fileHashes:{}},releases:{'0.2.5':{status:'development',summary:'Fixture',changes:[{id:'feature',category:'Added',brief:'Literal <script>unsafe</script>',details:['Actual feature behavior.'],files:['feature.txt','scripts/templates/guide.html']}]}}};
  write('CHANGELOG.json',JSON.stringify(log));write('feature.txt','changed');
  const run=(...args)=>spawnSync(process.execPath,[path.join(root,'scripts/changelog.mjs'),...args,'--root',fixture],{encoding:'utf8'});
  const ignoreFixture=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  ignoreFixture.releases['0.2.5'].changes[0].files.push('.gitignore','local-only.txt');
  write('CHANGELOG.json',JSON.stringify(ignoreFixture));
  write('.gitignore','local-only.txt\n');
  git('rm','--cached','--','local-only.txt');
  assert.equal(run('check').status,1,'uncheckpointed change fails');
  const checkpoint=run('checkpoint');assert.equal(checkpoint.status,0,checkpoint.stderr);
  const checked=run('check');assert.equal(checked.status,0,checked.stderr);
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8')).development.fileHashes['local-only.txt'],'deleted','untracked ignored files fingerprint as repository deletions');
  assert.equal(readFileSync(path.join(fixture,'local-only.txt'),'utf8'),'keep this local copy','untracking preserves local files');
  rmSync(path.join(fixture,'local-only.txt'));
  assert.equal(run('check').status,0,'audit is identical when ignored local copies are absent');
  const guide=readFileSync(path.join(fixture,'scripts/templates/guide.html'),'utf8');
  assert.ok(guide.includes('&lt;script&gt;unsafe&lt;/script&gt;'),'notes are escaped');
  assert.ok(!readFileSync(path.join(fixture,'extension/guide.html'),'utf8').includes('<script>'),'extension has no inline executable scripts');
  assert.equal(readFileSync(path.join(fixture,'app/public/legal.html'),'utf8'),readFileSync(path.join(fixture,'scripts/templates/legal.html'),'utf8'),'bundled legal page matches its source');
  assert.ok(!readFileSync(path.join(fixture,'extension/legal.html'),'utf8').includes('<script>'),'extension legal page has no inline executable scripts');
  assert.ok(readFileSync(path.join(fixture,'extension/legal.js'),'utf8').includes('window.legalFixture=true;'));
  assert.equal(run('sync').status,0);assert.equal(run('check').status,0,'generation is idempotent');
  const standalone=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  standalone.historyStartVersion='0.2.5';
  standalone.development.previousVersion=null;
  standalone.releases['0.2.4']={status:'historical',summary:'Original project snapshot',changes:[]};
  write('CHANGELOG.json',JSON.stringify(standalone));
  assert.equal(run('sync').status,0);
  const standaloneGuide=readFileSync(path.join(fixture,'scripts/templates/guide.html'),'utf8');
  assert.ok(standaloneGuide.includes('First standalone release'));
  assert.ok(!standaloneGuide.includes('release-0.2.4'),'pre-standalone history is retained in the source but excluded from public pages');
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8')).releases['0.2.4'].status,'historical');
  write('feature.txt','changed again');assert.equal(run('check').status,1,'later change invalidates fingerprint');
  assert.equal(run('checkpoint').status,0);
  write('missing.txt','undocumented');assert.equal(run('checkpoint').status,1,'untracked file needs notes');
  rmSync(path.join(fixture,'missing.txt'));rmSync(path.join(fixture,'feature.txt'));
  assert.equal(run('check').status,1,'deletion needs a new checkpoint');assert.equal(run('checkpoint').status,0);
  const beforeTransfer=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  assert.equal(run('start','0.2.6','0.2.5').status,1,'logged notes require an explicit transfer choice');
  assert.equal(run('start','0.2.6','0.2.5','--transfer').status,0);
  const updated=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  assert.equal(updated.development.previousVersion,'0.2.5');
  assert.equal(updated.releases['0.2.5'].status,'superseded');
  assert.equal(updated.releases['0.2.5'].supersededBy,'0.2.6');
  assert.equal(updated.releases['0.2.5'].changes.length,0,'draft notes move rather than appear twice');
  assert.equal(updated.releases['0.2.6'].changes[0].id,'feature','unpublished notes follow the development version');
  assert.equal(updated.releases['0.2.6'].transferredFrom,'0.2.5');
  assert.ok(updated.releases['0.2.6'].changes.some(change=>change.id==='version-0.2.6'));
  const lock=JSON.parse(readFileSync(path.join(fixture,'app/package-lock.json'),'utf8'));
  assert.equal(lock.version,'0.2.6');assert.equal(lock.packages[''].version,'0.2.6');
  assert.equal(lock.packages['node_modules/example'].version,'2.0.0','dependency versions stay pinned');
  const cargoLock=readFileSync(path.join(fixture,'app/src-tauri/Cargo.lock'),'utf8');
  assert.ok(cargoLock.includes('name = "zoltraak-app"\nversion = "0.2.6"'));
  assert.ok(cargoLock.includes('name = "third-party"\nversion = "2.0.0"'));
  assert.equal(run('start','0.2.6','0.2.5').status,0);
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8')).releases['0.2.6'].changes.length,2,'repeating version update is idempotent');
  updated.releases['0.2.6'].status='released';
  write('CHANGELOG.json',JSON.stringify(updated));
  assert.equal(run('start','0.2.7','0.2.6').status,0);
  const next=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  assert.equal(next.releases['0.2.7'].changes.length,1,'published feature notes are not copied into the next release');
  assert.equal(next.releases['0.2.7'].changes[0].id,'version-0.2.7');
  write('CHANGELOG.json',JSON.stringify(beforeTransfer));
  assert.equal(run('start','0.2.6','0.2.5','--keep').status,0);
  const kept=JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8'));
  assert.equal(kept.releases['0.2.5'].changes[0].id,'feature');
  assert.equal(kept.releases['0.2.6'].changes.length,1,'No keeps feature notes on the old version');
  write('CHANGELOG.json',JSON.stringify(beforeTransfer));
  const canceled=spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'scripts/set_version.ps1'),'0.2.6','-ProjectRoot',fixture],{input:'q\n',encoding:'utf8'});
  assert.equal(canceled.status,0,canceled.stderr);
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'app/package.json'),'utf8')).version,'0.2.5','cancel leaves version files untouched');
  const accepted=spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'scripts/set_version.ps1'),'0.2.6','-ProjectRoot',fixture],{input:'y\n',encoding:'utf8'});
  assert.equal(accepted.status,0,accepted.stderr);
  assert.ok(accepted.stdout.includes('Transfer these changes'));
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8')).releases['0.2.6'].transferredFrom,'0.2.5');
  write('CHANGELOG.json',JSON.stringify(beforeTransfer));
  write('app/package.json','{"version":"0.2.5"}');write('app/src-tauri/tauri.conf.json','{"version":"0.2.5"}');
  const declined=spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'scripts/set_version.ps1'),'0.2.6','-ProjectRoot',fixture],{input:'n\n',encoding:'utf8'});
  assert.equal(declined.status,0,declined.stderr);
  assert.equal(JSON.parse(readFileSync(path.join(fixture,'CHANGELOG.json'),'utf8')).releases['0.2.5'].changes[0].id,'feature','No preserves the preceding draft');
  assert.equal(run('check').status,0,'a version-only bump after No respects the previous documentation baseline');
 }finally{rmSync(fixture,{recursive:true,force:true});}
});
